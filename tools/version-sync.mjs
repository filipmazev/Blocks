import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

import { formatGeneratedTypeScript } from './helpers/generated-typescript.helpers.mjs';
import { resolveReleaseVersion } from './helpers/release-version.helpers.mjs';

const pkg = JSON.parse(readFileSync(new URL('../projects/blocks/package.json', import.meta.url), 'utf8'));
const lockPath = new URL('../package-lock.json', import.meta.url);
const lock = JSON.parse(readFileSync(lockPath, 'utf8'));

if (lock.packages['projects/blocks'].version !== pkg.version) {
  lock.packages['projects/blocks'].version = pkg.version;
  writeFileSync(lockPath, JSON.stringify(lock, null, 4) + '\n');
}

const channel = pkg.publishConfig?.tag ?? 'latest';
const constants = {
  BLOCKS_VERSION: pkg.version,
  BLOCKS_RELEASE_CHANNEL: channel,
  BLOCKS_VERSION_LABEL: `v${pkg.version}${channel === 'latest' ? '' : ` (${channel})`}`
};
const content = `/* Public API Surface of blocks. Generated by tools/version-sync.mjs; do not edit. */

${Object.entries(constants)
  .map(([name, value]) => `export const ${name} = ${JSON.stringify(value)};`)
  .join('\n')}
`;

const target = new URL('../projects/blocks/constants/version.constants.ts', import.meta.url);

mkdirSync(new URL('../projects/blocks/constants', import.meta.url), { recursive: true });

writeFileSync(target, await formatGeneratedTypeScript(content, target));

const entry = new URL('../projects/blocks/public-api.ts', import.meta.url);
const entryContent = `/* Public API Surface of blocks. Generated by tools/version-sync.mjs; do not edit. */
export * from '@blocks/constants/version.constants';
`;

writeFileSync(entry, await formatGeneratedTypeScript(entryContent, entry));

const releaseConfig = JSON.parse(readFileSync(new URL('../release.config.json', import.meta.url), 'utf8'));
const nextVersion = resolveReleaseVersion(pkg, releaseConfig.nextVersion);
const playgroundTarget = new URL('../projects/playground/src/app/generated/release.ts', import.meta.url);
const playgroundContent = `// Generated by tools/version-sync.mjs. Do not edit.
export const PLAYGROUND_VERSION: string = ${JSON.stringify(nextVersion)};
`;

writeFileSync(playgroundTarget, await formatGeneratedTypeScript(playgroundContent, playgroundTarget));
